// Download the Whisper speech models into site/assets/models/, from pinned Hugging Face
// revisions, and record every file's size and SHA-256 in manifest.json.
//   node scripts/fetch-models.mjs            download what is missing, verify everything
//   node scripts/fetch-models.mjs --check    verify the committed files against the manifest only
// The files are committed to the repository (the largest is ~54 MB), so the site serves them
// itself and neither a deploy nor a visitor depends on Hugging Face being reachable.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "site/assets/models");
const MANIFEST = path.join(OUT, "manifest.json");
const checkOnly = process.argv.includes("--check");

// q8 ("_quantized") weights: the smallest files that run on the WebAssembly CPU backend.
// The "_timestamped" exports include the cross-attention outputs that word-level timing needs.
export const MODELS = [
  { id: "whisper-tiny.en", repo: "onnx-community/whisper-tiny.en_timestamped", revision: "aeaa13760958b03fac5062f457d317d3319c3168", label: "Whisper tiny (English)", license: "Apache-2.0 (model card of openai/whisper-tiny.en; original release MIT)" },
  { id: "whisper-base", repo: "onnx-community/whisper-base_timestamped", revision: "608c49e61301901684bc36cac8f74b95ff6b5a8e", label: "Whisper base (multilingual)", license: "Apache-2.0 (model card of openai/whisper-base; original release MIT)" },
];
const FILES = [
  "config.json", "generation_config.json", "preprocessor_config.json", "tokenizer.json", "tokenizer_config.json",
  "onnx/encoder_model_quantized.onnx", "onnx/decoder_model_merged_quantized.onnx",
];

const sha256 = (file) => new Promise((resolve, reject) => {
  const h = crypto.createHash("sha256");
  fs.createReadStream(file).on("data", (d) => h.update(d)).on("end", () => resolve(h.digest("hex"))).on("error", reject);
});

const old = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : { models: [] };
const manifest = { note: "Generated by scripts/fetch-models.mjs. Whisper by OpenAI; ONNX exports by the onnx-community organisation on Hugging Face.", models: [] };
let bad = 0;

for (const m of MODELS) {
  const before = old.models.find((x) => x.id === m.id && x.revision === m.revision);
  const entry = { id: m.id, label: m.label, source: `https://huggingface.co/${m.repo}/tree/${m.revision}`, revision: m.revision, license: m.license, files: [] };
  for (const f of FILES) {
    const dst = path.join(OUT, m.id, f);
    if (!fs.existsSync(dst)) {
      if (checkOnly) { console.log(`MISSING ${m.id}/${f}`); bad++; continue; }
      const url = `https://huggingface.co/${m.repo}/resolve/${m.revision}/${f}`;
      process.stdout.write(`get ${m.id}/${f} ... `);
      const res = await fetch(url, { redirect: "follow" });
      if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.writeFileSync(dst, Buffer.from(await res.arrayBuffer()));
      console.log(`${(fs.statSync(dst).size / 1e6).toFixed(1)} MB`);
    }
    const rec = { path: f, bytes: fs.statSync(dst).size, sha256: await sha256(dst) };
    const was = before?.files.find((x) => x.path === f);
    if (was && (was.sha256 !== rec.sha256 || was.bytes !== rec.bytes)) { console.log(`CHANGED ${m.id}/${f}: the file no longer matches manifest.json`); bad++; }
    entry.files.push(rec);
  }
  entry.bytes = entry.files.reduce((s, f) => s + f.bytes, 0);
  manifest.models.push(entry);
  console.log(`${m.id}: ${entry.files.length} files, ${(entry.bytes / 1e6).toFixed(1)} MB`);
}

if (bad) { console.error(`${bad} problem(s)`); process.exit(1); }
if (!checkOnly) fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1) + "\n");
console.log(checkOnly ? "models match the manifest" : "wrote manifest.json");
